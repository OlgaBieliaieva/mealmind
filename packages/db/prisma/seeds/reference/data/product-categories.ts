/**
 * Parent-first order is required by a sequential database upsert. In
 * particular, the new poultry node must exist before the preserved chicken and
 * turkey rows are written.
 */
export const PRODUCT_CATEGORIES = orderParentFirst([
  ...PROTOTYPE_PRODUCT_CATEGORY_SEED,
  ...USDA_EXTENSION_PRODUCT_CATEGORY_SEED,
]);

function orderParentFirst(
  definitions: readonly ProductCategorySeedData[],
): readonly ProductCategorySeedData[] {
  const remaining = new Map(definitions.map((definition) => [definition.id, definition]));
  const ordered: ProductCategorySeedData[] = [];
  const insertedIds = new Set<string>();

  while (remaining.size > 0) {
    const ready = [...remaining.values()].filter(
      (definition) =>
        definition.parentCategoryId === null || insertedIds.has(definition.parentCategoryId),
    );

    if (ready.length === 0) {
      throw new Error("ProductCategory seed contains a missing parent or hierarchy cycle");
    }

    for (const definition of ready) {
      ordered.push(definition);
      insertedIds.add(definition.id);
      remaining.delete(definition.id);
    }
  }

  return ordered;
}
